#!/usr/bin/env node
/**
 * Assembles the GitBook tree (gitbook/) from generated + hand-written sources.
 *
 *  1. (unless --summary-only) runs the forge-doc cleaner for every package in
 *     docs.config.json, rewriting the generated reference subtrees. Requires
 *     `forge doc` output (pnpm docs:gen) to exist.
 *  2. Writes an index README.md per reference subtree.
 *  3. Scans the committed gitbook/<sdkReferenceDir>/ (delivered by the
 *     summerfi-monorepo docs workflow) for SDK reference pages.
 *  4. Renders gitbook/SUMMARY.md from summary.template.md, expanding the
 *     <!-- @generated:contracts --> and <!-- @generated:sdk-reference -->
 *     markers.
 *
 * Generated areas are wholly owned by this script (wiped on each run); pages
 * outside them are never touched. Zero npm dependencies — must run under bare
 * Node in the CI of both repos (the monorepo delivery workflow runs it with
 * --summary-only and no pnpm install).
 */

import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { cleanPackage } from './clean-forge-docs.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..', '..')
const GITBOOK = path.join(ROOT, 'gitbook')
const CONFIG = JSON.parse(fs.readFileSync(path.join(HERE, 'docs.config.json'), 'utf8'))

const summaryOnly = process.argv.includes('--summary-only')

function pageTitle(file) {
  const text = fs.readFileSync(file, 'utf8')
  const m = text.match(/^# (.+)$/m)
  return m ? m[1].trim() : path.basename(file, '.md')
}

/** Render one reference subtree's SUMMARY entries from its _nav.json. */
function contractEntries() {
  const lines = []
  for (const entry of CONFIG.contracts) {
    const outDir = path.join(GITBOOK, entry.out)
    const navPath = path.join(outDir, '_nav.json')
    if (!fs.existsSync(navPath)) {
      console.warn(`warn: ${entry.package} has no _nav.json under ${entry.out} — skipped`)
      continue
    }
    const nav = JSON.parse(fs.readFileSync(navPath, 'utf8'))
    lines.push(`* [${entry.section}](${path.posix.join(entry.out, 'README.md')})`)
    for (const group of nav.tree) {
      for (const page of group.pages) {
        lines.push(`  * [${page.title}](${page.file.split(path.sep).join('/')})`)
      }
    }
  }
  return lines
}

/** Write an index page per reference subtree (generated area). */
function writeReferenceIndexes() {
  for (const entry of CONFIG.contracts) {
    const outDir = path.join(GITBOOK, entry.out)
    const navPath = path.join(outDir, '_nav.json')
    if (!fs.existsSync(navPath)) continue
    const nav = JSON.parse(fs.readFileSync(navPath, 'utf8'))
    const lines = [
      '---',
      `description: Generated API reference for the ${entry.package} package.`,
      '---',
      '',
      `<!-- AUTOGENERATED by scripts/docs/assemble.mjs — do not edit. -->`,
      '',
      `# ${entry.section} Reference`,
      '',
      `Generated from the NatSpec of [\`packages/${nav.package}\`](https://github.com/OasisDEX/summer-earn-protocol/tree/main/packages/${nav.package}).`,
      '',
    ]
    for (const group of nav.tree) {
      if (group.dir) lines.push(`## ${group.dir}`, '')
      for (const page of group.pages) {
        const rel = path.relative(outDir, path.join(GITBOOK, page.file)).split(path.sep).join('/')
        lines.push(`* [${page.title}](${rel})`)
      }
      lines.push('')
    }
    fs.writeFileSync(path.join(outDir, 'README.md'), lines.join('\n').trimEnd() + '\n')
  }
}

// The SDK reference is published from the summerfi-monorepo's own GitBook
// space (Site-with-tabs model); it is no longer delivered into this repo.

function main() {
  if (!summaryOnly) {
    for (const entry of CONFIG.contracts) {
      const pkgDir = path.join(ROOT, 'packages', entry.package)
      const outDir = path.join(GITBOOK, entry.out)
      if (!fs.existsSync(path.join(pkgDir, 'docs', 'generated', 'src'))) {
        console.warn(`warn: ${entry.package} has no forge doc output (run pnpm docs:gen) — skipped`)
        continue
      }
      // forge falls back to contracts/ when the package has no src/ dir
      const srcDirName = fs.existsSync(path.join(pkgDir, 'src')) ? 'src' : 'contracts'
      const nav = cleanPackage(pkgDir, outDir, `packages/${entry.package}`, GITBOOK, srcDirName)
      console.log(`${entry.package}: ${nav.tree.reduce((n, g) => n + g.pages.length, 0)} pages → ${entry.out}`)
    }
    writeReferenceIndexes()
  }

  const template = fs.readFileSync(path.join(HERE, 'summary.template.md'), 'utf8')
  const summary = template.replace('<!-- @generated:contracts -->', contractEntries().join('\n'))
  fs.writeFileSync(path.join(GITBOOK, 'SUMMARY.md'), summary)
  console.log('SUMMARY.md rendered')
}

main()
